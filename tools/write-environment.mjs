import { writeFileSync } from 'node:fs';

const REQUIRED = ['SUPABASE_URL', 'SUPABASE_ANON_KEY', 'SPOTIFY_CLIENT_ID', 'SPOTIFY_REDIRECT_URI'];
const TARGET = 'apps/web/src/environments/environment.deploy.ts';

function fail(message) {
  console.error(`write-environment: ${message}`);
  process.exit(1);
}

function isServiceRoleKey(key) {
  if (key.startsWith('sb_secret_')) {
    return true;
  }

  try {
    const payload = JSON.parse(Buffer.from(key.split('.')[1] ?? '', 'base64url').toString());

    return payload.role === 'service_role';
  } catch {
    return false;
  }
}

const missing = REQUIRED.filter((name) => !process.env[name]?.trim());

if (missing.length > 0) {
  fail(`missing environment variables: ${missing.join(', ')}`);
}

const values = Object.fromEntries(REQUIRED.map((name) => [name, process.env[name].trim()]));

for (const name of ['SUPABASE_URL', 'SPOTIFY_REDIRECT_URI']) {
  if (new URL(values[name]).protocol !== 'https:') {
    fail(`${name} must be an https URL`);
  }
}

// The service_role key must never reach the browser bundle.
if (isServiceRoleKey(values.SUPABASE_ANON_KEY)) {
  fail('SUPABASE_ANON_KEY looks like a service_role key; use the anon/publishable key');
}

const environment = {
  supabaseUrl: values.SUPABASE_URL,
  supabaseAnonKey: values.SUPABASE_ANON_KEY,
  spotifyClientId: values.SPOTIFY_CLIENT_ID,
  spotifyRedirectUri: values.SPOTIFY_REDIRECT_URI,
};

writeFileSync(
  TARGET,
  `// Generated by tools/write-environment.mjs; do not edit or commit.\nexport const environment = ${JSON.stringify(environment, null, 2)};\n`,
);
console.log(`write-environment: wrote ${TARGET}`);
